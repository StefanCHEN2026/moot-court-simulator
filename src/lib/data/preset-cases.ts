import { CaseType, RoleId } from '@/types/court';

/** 证据条目 */
export interface EvidenceItem {
  id: string;
  name: string;
  /** 证据类型 */
  type: '物证' | '书证' | '证人证言' | '鉴定意见' | '勘验笔录' | '视听资料' | '电子数据' | '当事人陈述';
  /** 证据来源 */
  source: '原告' | '被告' | '公诉机关' | '法院调取';
  /** 证明目的 */
  purpose: string;
  /** 证据内容摘要 */
  summary: string;
  /** 证据图片URL */
  imageUrl?: string;
}

/** 案件材料 */
export interface CaseMaterial {
  id: string;
  /** 材料标题 */
  title: string;
  /** 材料分类 */
  category: '起诉状' | '答辩状' | '证据' | '其他材料';
  /** 所属方 */
  party?: '原告' | '被告' | '公诉机关';
  /** 材料内容（起诉状/答辩状/其他材料的正文；证据材料可为空，证据清单在 evidenceList 中） */
  content?: string;
  /** 证据清单（仅 category=证据 时使用） */
  evidenceList?: EvidenceItem[];
  /** 目录项（用于证据卷宗合成目录） */
  toc?: { title: string; anchor: string }[];
}

export interface PresetCase {
  id: string;
  caseType: CaseType;
  caseName: string;
  caseDescription: string;
  defaultRole: RoleId;
  tags: string[];
  /** 难度等级：1-5星 */
  starLevel: 1 | 2 | 3 | 4 | 5;
  difficulty: '入门' | '进阶' | '挑战';
  summary: string;
  /** 副本图标类型 */
  iconType: 'balance' | 'document' | 'home' | 'car' | 'briefcase';
  /** 副本封面图 URL */
  imageUrl?: string;
  /** 通关奖励描述 */
  rewards: string[];
  materials: CaseMaterial[];
}

